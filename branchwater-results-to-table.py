#!/usr/bin/env python3

import argparse
import logging
import os
import csv
from datetime import date
from pathlib import Path
from tqdm import tqdm

logging.basicConfig(level=logging.INFO)

HEADER = ["Run", "Genome_Mgnify_accession", "Containment", "cANI"]
CONTAINMENT_THRESHOLD = 0.5


def main():
    args = parse_args()

    input_csv = Path(args.input_csv)
    output_folder = Path(args.output_folder)

    os.makedirs(output_folder, exist_ok=True)
    date_suffix = date.today().isoformat()
    combined_output_path = output_folder / f"full_phase2_linkage_table_{date_suffix}.tsv"

    # The script makes both a combined output table and individual tables per catalogue
    # Start the combined output file and print the header to it
    with combined_output_path.open("w", newline="") as combined_out:
        full_writer = csv.writer(combined_out, delimiter="\t")
        full_writer.writerow(HEADER)

        with input_csv.open(newline="") as csv_in:
            samplesheet_reader = csv.reader(csv_in)
            for catalogue, branchwater_folder, metadata_table in samplesheet_reader:
                process_catalogue(
                    catalogue=catalogue,
                    branchwater_folder=Path(branchwater_folder),
                    metadata_table=Path(metadata_table),
                    output_folder=output_folder,
                    date_suffix=date_suffix,
                    full_writer=full_writer,
                )


def process_catalogue(
    catalogue: str,
    branchwater_folder: Path,
    metadata_table: Path,
    output_folder: Path,
    date_suffix: str,
    full_writer,
):
    logging.info(f"Processing catalogue {catalogue}")

    species_reps = load_metadata_table(metadata_table)
    logging.info(f"Expecting {len(species_reps)} species representatives")

    csv_files, missing = get_csvs(branchwater_folder, species_reps)
    if missing:
        raise FileNotFoundError(
            f"Missing CSV files for catalogue {catalogue}:\n" +
            "\n".join(sorted(missing))
        )

    catalogue_path = output_folder / f"{catalogue}_phase2_linkage_table_{date_suffix}.tsv"

    with catalogue_path.open("w", newline="") as cat_out:
        writer = csv.writer(cat_out, delimiter="\t")
        writer.writerow(HEADER)

        # Loop through all CSV files generated by branchwater
        for csv_file in tqdm(csv_files, desc=f"{catalogue}", unit="file"):
            process_branchwater_file(
                branchwater_folder / csv_file,
                writer,
                full_writer
            )


def process_branchwater_file(path: Path, catalogue_writer, full_writer):
    with path.open(newline="") as infile:
        reader = csv.DictReader(infile)

        for row in reader:
            containment_raw = row.get("containment")
            if containment_raw is None:
                raise KeyError(f"'containment' column missing in {path.name}")

            try:
                containment = float(containment_raw)
            except ValueError:
                raise ValueError(f"Invalid containment value '{containment_raw}' in {path.name}")

            if containment < CONTAINMENT_THRESHOLD:
                continue

            run = row.get("match_name")
            genome_raw = row.get("query_name")
            cani = row.get("query_containment_ani")

            genome = genome_raw.split("_", 1)[0]  # remove underscore and everything after

            record = [run, genome, containment, cani]
            catalogue_writer.writerow(record)
            full_writer.writerow(record)


def load_metadata_table(metadata_table):
    species_reps = set()
    with open(metadata_table, newline="") as metadata_in:
        metadata_reader = csv.DictReader(metadata_in, delimiter="\t")
        for row in metadata_reader:
            species_reps.add(row["Species_rep"])
    return species_reps


def get_csvs(folder_path, species_reps):
    expected = {f"{rep}.csv" for rep in species_reps}
    found = {f for f in os.listdir(folder_path) if f.endswith(".csv")}

    missing = expected - found
    csv_files = sorted(expected)

    return csv_files, missing


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Produce genome-to-assembly linkage tables from per-genome "
            "branchwater results."
        ),
        formatter_class=argparse.RawTextHelpFormatter,
    )

    parser.add_argument(
        "-i", "--input_csv",
        required=True,
        help="No-header CSV with: catalogue name, branchwater results folder, catalogue metadata table"
    )
    parser.add_argument(
        "-o", "--output_folder",
        required=True,
        help="Output directory (created if missing)"
    )

    return parser.parse_args()


if __name__ == "__main__":
    main()
